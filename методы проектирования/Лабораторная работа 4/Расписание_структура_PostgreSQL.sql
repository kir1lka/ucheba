-- Структура PostgreSQL по текущим JPA-классам курсового проекта Расписание.
-- 15 таблиц, 11 внешних ключей. Скрипт предназначен для пустой базы.
-- Ссылки attendance_* без JPA-связей не дополнены внешними ключами.


    create table attendance_mark (
        id bigint generated by default as identity,
        group_id bigint not null,
        lesson_date date not null,
        lesson_id bigint not null,
        lesson_time time(0),
        mark varchar(1) not null,
        student_id bigint not null,
        subject varchar(255),
        primary key (id),
        unique (student_id, lesson_id, lesson_date)
    );

    create table attendance_student (
        id bigint generated by default as identity,
        archived boolean not null,
        group_id bigint not null,
        name varchar(150) not null,
        primary key (id)
    );

    create table groups (
        id bigint generated by default as identity,
        code varchar(32),
        number integer,
        shift varchar(255) check ((shift in ('MORNING','AFTERNOON'))),
        curator_id bigint,
        primary key (id)
    );

    create table holiday (
        id bigint generated by default as identity,
        end_date date not null,
        name varchar(255),
        start_date date not null,
        type varchar(255) not null check ((type in ('HOLIDAY','VACATION'))),
        yearly boolean default false,
        primary key (id)
    );

    create table lesson (
        id bigint generated by default as identity,
        custom_time boolean default false,
        date date,
        day_of_week varchar(255) check ((day_of_week in ('MONDAY','TUESDAY','WEDNESDAY','THURSDAY','FRIDAY','SATURDAY','SUNDAY'))),
        description text,
        end_time time(0),
        order_number integer,
        special boolean default false,
        time time(0),
        title varchar(255),
        group_id bigint,
        studio_id bigint,
        primary key (id)
    );

    create table lesson_photos (
        lesson_id bigint not null,
        photo text
    );

    create table login_history (
        id bigint generated by default as identity,
        ip_address varchar(64) not null,
        logged_at timestamp(6) with time zone not null,
        user_id bigint not null,
        primary key (id)
    );

    create table push_subscription (
        id bigint generated by default as identity,
        auth varchar(255) not null,
        endpoint varchar(1000) not null unique,
        p256dh varchar(255) not null,
        primary key (id)
    );

    create table studio (
        id bigint generated by default as identity,
        code varchar(255),
        description text,
        name varchar(255),
        teacher_photo text,
        primary key (id)
    );

    create table studio_photos (
        studio_id bigint not null,
        photo text
    );

    create table sub_task (
        id bigint generated by default as identity,
        completed boolean not null,
        description varchar(500) not null,
        task_id bigint not null,
        primary key (id)
    );

    create table task_history (
        id bigint generated by default as identity,
        action varchar(40) not null,
        changed_at timestamp(6) with time zone not null,
        new_state text not null,
        old_state text,
        user_id bigint not null,
        task_id bigint not null,
        primary key (id)
    );

    create table tasks (
        id bigint generated by default as identity,
        category varchar(100) not null,
        created_at timestamp(6) with time zone not null,
        deleted boolean not null,
        description text not null,
        priority varchar(255) not null check ((priority in ('LOW','NORMAL','HIGH'))),
        status varchar(255) not null check ((status in ('TODO','IN_PROGRESS','DONE'))),
        title varchar(200) not null,
        user_id bigint not null,
        primary key (id)
    );

    create table teacher (
        id bigint generated by default as identity,
        birth_date date,
        full_name varchar(255),
        phone varchar(255),
        studio_id bigint unique,
        primary key (id)
    );

    create table users (
        id bigint generated by default as identity,
        email varchar(255) not null unique,
        full_name varchar(255),
        login varchar(255) not null unique,
        password_hash varchar(255) not null,
        role varchar(255) not null check ((role in ('ADMIN','TEACHER','STUDENT','METHODIST'))),
        primary key (id)
    );

